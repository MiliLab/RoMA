    def _global_pool(self, x: torch.Tensor, token_position: Optional[Union[int, List[int]]] = 0 
                     ) -> Tuple[torch.Tensor, torch.Tensor]:
    
        if self.pool_type == 'avg':
            pooled, tokens = x.mean(dim=1), x
        else:  # 'tok'
            pos = 0 if token_position is None else token_position
            if isinstance(pos, list):
                pos = pos[0]
            pooled = x[:, pos]
            mask = torch.ones(x.shape[1], device=x.device, dtype=torch.bool)
            mask[pos] = False
            tokens = x[:, mask, :]
        return pooled, tokens
    
    def _pool(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:

        if self.attn_pool is not None:
            if self.attn_pool_contrastive is not None:
                # This is untested, WIP pooling that should match paper
                # x = self.ln_post(x)  # TBD LN first or separate one after each pool?
                x = self.ln_pre(x)  # (b, 170, 768)
                tokens = self.attn_pool(x) # (b, n_queries, output_dim=512)

                if self.attn_pool_type == 'parallel':
                    pooled = self.attn_pool_contrastive(x) 
                    if pooled.dim() == 3 and pooled.shape[1] == 1:
                        pooled = pooled[:, 0]  # [B,1,D] -> [B,D]
                else:
                    assert self.attn_pool_type == 'cascade' 
                    pooled = self.attn_pool_contrastive(tokens)
            else: # this is the original OpenCLIP CoCa setup, does not match paper
                x = self.attn_pool(x)  
                x = self.ln_post(x)    
                pooled, tokens = self._global_pool(x) 
        elif self.final_ln_after_pool:
            pooled, tokens = self._global_pool(x)
            pooled = self.ln_post(pooled)
        else:
            x = self.ln_post(x)
            pooled, tokens = self._global_pool(x)
        return pooled, tokens
    

    def forward_features(self, 
                         x, 
                         x_starts, 
                         y_starts,
                         crop_size,
                         inference_params=None, 
                         if_random_cls_token_position=False, 
                         if_random_token_rank=False):
        # taken from https://github.com/rwightman/pytorch-image-models/blob/master/timm/models/vision_transformer.py
        # with slight modifications to add the dist_token
        x = self.patch_embed(x)
        B, M, C = x.shape
        H, W = int(np.sqrt(M)), int(np.sqrt(M))
        
        # Adaptive Rotation Encoding (only when crop info provided)
        if crop_size is None:
            pass
        else:
            rotation_mask = torch.zeros(B, H * W, device=x.device, dtype=torch.bool)
            token_per_pixel = 16

            for batch_idx in range(B):
                current_crop_size = crop_size[batch_idx]
                current_x_starts = x_starts[batch_idx]
                current_y_starts = y_starts[batch_idx]

                x_start_token = (current_x_starts / token_per_pixel).long()
                y_start_token = (current_y_starts / token_per_pixel).long()
                crop_span = (current_crop_size / token_per_pixel).long()

                x_indices = torch.arange(
                    x_start_token.item(),
                    x_start_token.item() + crop_span.item(),
                    device=x.device,
                    dtype=torch.long
                )
                y_indices = torch.arange(
                    y_start_token.item(),
                    y_start_token.item() + crop_span.item(),
                    device=x.device,
                    dtype=torch.long
                )

                grid_indices = y_indices * W + x_indices
                rotation_mask[batch_idx, grid_indices] = True

            angle_embed_expanded = self.angle_embed.expand(B, H * W, C)
            x = x + angle_embed_expanded * rotation_mask.unsqueeze(-1)


        if self.if_cls_token:
            if self.use_double_cls_token:
                cls_token_head = self.cls_token_head.expand(B, -1, -1).contiguous()
                cls_token_tail = self.cls_token_tail.expand(B, -1, -1).contiguous()
                token_position = [0, M + 1]
                x = torch.cat((cls_token_head, x, cls_token_tail), dim=1)
                M = x.shape[1]
            else:
                if self.use_middle_cls_token:
                    cls_token = self.cls_token.expand(B, -1, -1).contiguous()
                    token_position = M // 2
                    # add cls token in the middle
                    x = torch.cat((x[:, :token_position, :], cls_token, x[:, token_position:, :]), dim=1)
                elif if_random_cls_token_position:
                    cls_token = self.cls_token.expand(B, -1, -1).contiguous()
                    token_position = random.randint(0, M)
                    x = torch.cat((x[:, :token_position, :], cls_token, x[:, token_position:, :]), dim=1)
                    print("token_position: ", token_position)
                else:
                    cls_token = self.cls_token.expand(B, -1, -1).contiguous()  # stole cls_tokens impl from Phil Wang, thanks
                    token_position = 0
                    x = torch.cat((cls_token, x), dim=1)
                M = x.shape[1]

        if self.if_abs_pos_embed:
            x = x + self.pos_embed
            x = self.pos_drop(x)

        if if_random_token_rank:
            shuffle_indices = torch.randperm(M)

            if isinstance(token_position, list):
                print("original value: ", x[0, token_position[0], 0], x[0, token_position[1], 0])
            else:
                print("original value: ", x[0, token_position, 0])
            print("original token_position: ", token_position)

            x = x[:, shuffle_indices, :]
            if isinstance(token_position, list):
                new_token_position = [torch.where(shuffle_indices == token_position[i])[0].item() for i in range(len(token_position))]
                token_position = new_token_position
            else:
                token_position = torch.where(shuffle_indices == token_position)[0].item()

            if isinstance(token_position, list):
                print("new value: ", x[0, token_position[0], 0], x[0, token_position[1], 0])
            else:
                print("new value: ", x[0, token_position, 0])
            print("new token_position: ", token_position)

        if_flip_img_sequences = False
        if self.flip_img_sequences_ratio > 0 and (self.flip_img_sequences_ratio - random.random()) > 1e-5:
            x = x.flip([1])
            if_flip_img_sequences = True

        # mamba impl
        residual = None
        hidden_states = x
        if not self.if_bidirectional:
            for layer in self.layers:

                if if_flip_img_sequences and self.if_rope:
                    hidden_states = hidden_states.flip([1])
                    if residual is not None:
                        residual = residual.flip([1])

                # rope about
                if self.if_rope:
                    hidden_states = self.rope(hidden_states)
                    if residual is not None and self.if_rope_residual:
                        residual = self.rope(residual)

                if if_flip_img_sequences and self.if_rope:
                    hidden_states = hidden_states.flip([1])
                    if residual is not None:
                        residual = residual.flip([1])

                hidden_states, residual = layer(
                    hidden_states, residual, inference_params=inference_params
                )
        else:
            # get two layers in a single for-loop
            for i in range(len(self.layers) // 2):
                if self.if_rope:
                    hidden_states = self.rope(hidden_states)
                    if residual is not None and self.if_rope_residual:
                        residual = self.rope(residual)

                hidden_states_f, residual_f = self.layers[i * 2](
                    hidden_states, residual, inference_params=inference_params
                )
                hidden_states_b, residual_b = self.layers[i * 2 + 1](
                    hidden_states.flip([1]), None if residual == None else residual.flip([1]), inference_params=inference_params
                )
                hidden_states = hidden_states_f + hidden_states_b.flip([1])
                residual = residual_f + residual_b.flip([1])

        if not self.fused_add_norm:
            if residual is None:
                residual = hidden_states
            else:
                residual = residual + self.drop_path(hidden_states)
            hidden_states = self.norm_f(residual.to(dtype=self.norm_f.weight.dtype))
        else:
            # Set prenorm=False here since we don't need the residual
            fused_add_norm_fn = rms_norm_fn if isinstance(self.norm_f, RMSNorm) else layer_norm_fn
            hidden_states = fused_add_norm_fn(
                self.drop_path(hidden_states),
                self.norm_f.weight,
                self.norm_f.bias,
                eps=self.norm_f.eps,
                residual=residual,
                prenorm=False,
                residual_in_fp32=self.residual_in_fp32,
            )
        
        return hidden_states


    def forward(self, x, 
                tops, 
                lefts, 
                crop_size,
                return_features=False, 
                inference_params=None, 
                if_random_cls_token_position=False, 
                if_random_token_rank=False):
        
        x = self.forward_features(
            x, 
            tops, 
            lefts, 
            crop_size,
            inference_params=inference_params,
            if_random_cls_token_position=if_random_cls_token_position, 
            if_random_token_rank=if_random_token_rank)  
        
        pooled, tokens = self._pool(x)  

        if self.proj is not None:
            pooled = pooled @ self.proj

        if self.output_tokens:  
            return pooled, tokens
        
        return pooled